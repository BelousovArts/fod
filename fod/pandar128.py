def elevation_grid_deg(step_deg: float = DENSE_ELEV_STEP_DEG) -> np.ndarray:
    """Равномерная сетка элевации с шагом плотной зоны, сверху вниз."""
    top = float(ELEVATION_DEG[0])
    bottom = float(ELEVATION_DEG[-1])
    n = int(round((top - bottom) / step_deg)) + 1
    return top - step_deg * np.arange(n, dtype=np.float64)
